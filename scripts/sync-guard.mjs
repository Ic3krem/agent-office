// The Claude Code plugin in bridge/ is installed on its own (only the bridge folder is copied), so the Security Guard must live inside it.
// guard/*.mjs (plus redact.mjs and permissions.mjs, which it imports) are the source of truth; this script writes a copy into bridge/guard/
// with the two parent-folder imports rewritten. `node scripts/sync-guard.mjs` writes it, `--check` only compares (the tests use that).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['guard/audit.mjs', 'guard/classify.mjs', 'guard/config.mjs', 'guard/hook.mjs', 'guard/normalise.mjs', 'guard/payload.mjs', 'guard/rules.mjs', 'guard/scan.mjs', 'guard/taint.mjs', 'redact.mjs', 'permissions.mjs'];
const HEADER = '// GENERATED by scripts/sync-guard.mjs from the repository root. Do not edit here: change the original and run `node scripts/sync-guard.mjs`.\n';

export function expected() {
  const out = {};
  for (const f of FILES) {
    let t = fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/\r\n/g, '\n');
    t = t.replace(/from '\.\.\/(redact|permissions)\.mjs'/g, "from './$1.mjs'");
    out[path.join('bridge', 'guard', path.basename(f))] = HEADER + t;
  }
  return out;
}
export function check() {
  const bad = [];
  for (const [rel, text] of Object.entries(expected())) { let cur = ''; try { cur = fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ } if (cur !== text) bad.push(rel); }
  return bad;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) { const bad = check(); if (bad.length) { console.error('out of date:\n' + bad.join('\n')); process.exit(1); } console.log('bridge/guard is up to date'); }
  else { fs.mkdirSync(path.join(ROOT, 'bridge', 'guard'), { recursive: true }); for (const [rel, text] of Object.entries(expected())) fs.writeFileSync(path.join(ROOT, rel), text); console.log('wrote bridge/guard'); }
}
